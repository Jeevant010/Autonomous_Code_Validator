"""Intake a real git repository and run the same deterministic gate on it.

The project pack only reads trees that someone prepared by hand. This module
closes that gap: it clones a real repository at a real commit, installs that
repository's own dependencies into a private directory, uses the repository's
own test suite as the behaviour signal, and runs a trusted PoC as the security
signal. A candidate is then judged as a patch against that repository.

Evidence boundary, unchanged from the project path:

* the PoC lives outside the repository tree, in a trusted task record;
* the functional suite is the repository's own tests, and a candidate may not
  modify them;
* the gate decides, and it reports a structured PoC verdict rather than an
  exit code.

Limits are explicit. This is process-level containment, not a sandbox: there is
no network namespace and no filesystem jail. Cloning and dependency installation
require network access, so they are separate, explicit steps.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import time
import uuid
from dataclasses import dataclass, field, replace
from pathlib import Path

from .models import (
    CheckerResult,
    CheckFinding,
    ProjectFileInfo,
    ProjectSpec,
)
from .projects import ISOLATION_WARNING, run_project_checkers
from .sandbox import SandboxPolicy
from .sandbox import run as run_sandboxed
from .verdict import PocVerdict, classify_poc

MAX_REPO_BYTES = 60_000_000
MAX_REPO_FILES = 8_000
DEFAULT_GIT_TIMEOUT = 300
DEFAULT_INSTALL_TIMEOUT = 600


class RepoIntakeError(RuntimeError):
    """Raised when a repository cannot be fetched or prepared."""


@dataclass(frozen=True)
class RepoSpec:
    """A real repository at a real commit, plus the trusted evidence to judge it.

    ``poc`` and ``functional`` are paths inside a task directory that is kept
    outside the cloned tree. That keeps the judge out of the code under test.
    """

    task_id: str
    title: str
    cwe: str
    summary: str
    repo_url: str
    commit: str
    task_dir: Path
    fix_commit: str = ""
    fix_tag: str = ""
    diff_paths: tuple[str, ...] = ()
    # Some projects do not keep every file a package needs in git. Files such as
    # a version module are generated by the build backend from git metadata.
    # ``bootstrap`` records the exact, reviewed command that recreates them, so
    # a checkout is importable without pretending the file was always there.
    bootstrap: tuple[str, ...] = ()

    poc: str = "poc/exploit.py"
    functional: str = "tests/test_functional.py"
    checker_include: tuple[str, ...] = ("**/*.py",)
    checker_exclude: tuple[str, ...] = (
        "tests/**",
        "poc/**",
        "**/__pycache__/**",
        "**/.pytest_cache/**",
    )
    install_targets: tuple[str, ...] = ()
    python_path_extra: tuple[str, ...] = ()
    source_root: str = "src"
    memory_mb: int = 768
    poc_timeout: int = 120
    test_timeout: int = 600
    protected_paths: tuple[str, ...] = ()
    clean_baseline: bool = False

    @property
    def poc_path(self) -> Path:
        return (self.task_dir / self.poc).resolve()

    @property
    def functional_path(self) -> Path:
        return (self.task_dir / self.functional).resolve()

    @property
    def functional_in_repo(self) -> bool:
        """True when the behaviour suite is the repository's own test file.

        The task may point at the repository's real suite instead of a small
        trusted file. That is a stronger behaviour signal, and it is still safe:
        the gate refuses any diff that touches a protected test path.
        """

        return self.functional.startswith("repo:")

    def functional_target(self, tree: Path) -> Path:
        if self.functional_in_repo:
            return tree / self.functional[len("repo:") :]
        return self.functional_path


@dataclass
class RepoResult:
    """Gate result for a patch applied to a real repository."""

    task_id: str
    title: str
    cwe: str
    repo_url: str
    commit: str
    run_id: str
    input_mode: str
    clone_dir: str
    files: list[ProjectFileInfo]
    total_files: int
    total_bytes: int
    total_lines: int
    changed_files: list[str]
    poc_exit: int
    poc_verdict: PocVerdict
    poc_output: str
    behavior_exit: int
    behavior_output: str
    security_pass: bool
    behavior_pass: bool
    checker_pass: bool
    accepted: bool
    oracle_exit: int
    oracle_verdict: PocVerdict
    oracle_output: str
    oracle_ok: bool
    reasons: list[str]
    findings: list[CheckFinding]
    checker_tool: str
    checker_results: dict[str, CheckerResult] = field(default_factory=dict)
    isolation: str = "process-limits-only"
    isolation_warning: str = ISOLATION_WARNING
    findings_truncated: bool = False
    elapsed_ms: int = 0
    provenance: dict[str, str] = field(default_factory=dict)

    @property
    def rejected_by(self) -> str:
        if self.accepted:
            return "none"
        if not self.oracle_ok:
            return "oracle"
        if not self.security_pass:
            return "poc"
        if not self.behavior_pass:
            return "behavior"
        if not self.checker_pass:
            return "checker"
        return "unknown"


def _git(arguments: list[str], cwd: Path | None = None, timeout: int = DEFAULT_GIT_TIMEOUT) -> str:
    if shutil.which("git") is None:
        raise RepoIntakeError("git is not installed")
    process = subprocess.run(
        ["git", *arguments],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=timeout,
    )
    if process.returncode != 0:
        detail = (process.stderr or process.stdout).strip()[:800]
        raise RepoIntakeError(f"git {' '.join(arguments)} failed: {detail}")
    return process.stdout


def _run_bootstrap(spec: RepoSpec, tree: Path) -> None:
    """Recreate files the project's build backend generates, if declared.

    Only an explicit, declared command runs here. Nothing is invented and
    nothing is fetched beyond what the task already lists. Commands run with the
    clone as the working directory, and a script shipped beside ``task.json`` is
    copied into the clone first so a declared step never needs an absolute path.
    """

    if not spec.bootstrap:
        return

    for entry in spec.task_dir.iterdir():
        if entry.is_file() and entry.name.startswith(".acv-bootstrap"):
            shutil.copyfile(entry, tree / entry.name)

    for command in spec.bootstrap:
        process = subprocess.run(
            command,
            shell=True,
            cwd=tree,
            capture_output=True,
            text=True,
            timeout=300,
        )
        if process.returncode != 0:
            detail = (process.stderr or process.stdout).strip()[:400]
            raise RepoIntakeError(f"bootstrap step failed ({command}): {detail}")


def clone(
    spec: RepoSpec,
    destination: Path | None = None,
) -> Path:
    """Clone one repository at one commit into a scratch directory."""

    target = destination or Path(tempfile.mkdtemp(prefix=f"acv-repo-{spec.task_id}-"))
    if target.exists() and any(target.iterdir()):
        raise RepoIntakeError(f"clone target is not empty: {target}")

    _git(
        ["clone", "--filter=blob:none", "--no-checkout", spec.repo_url, str(target)],
        timeout=DEFAULT_GIT_TIMEOUT,
    )
    _git(["checkout", "--detach", spec.commit], cwd=target)

    head = _git(["rev-parse", "HEAD"], cwd=target).strip()
    # An annotated tag is not a commit; it points at one. Peel both sides to a
    # commit before comparing, otherwise a tag id never matches the checkout.
    pinned = _git(["rev-parse", f"{spec.commit}^{{commit}}"], cwd=target).strip()
    if head != pinned:
        raise RepoIntakeError(
            f"checked out {head}, which is not the pinned commit {pinned} ({spec.commit})"
        )

    _run_bootstrap(spec, target)

    files = [path for path in target.rglob("*") if path.is_file() and ".git" not in path.parts]
    total_bytes = sum(path.stat().st_size for path in files)
    if len(files) > MAX_REPO_FILES:
        raise RepoIntakeError(
            f"repository has {len(files)} files, above the {MAX_REPO_FILES} limit"
        )
    if total_bytes > MAX_REPO_BYTES:
        raise RepoIntakeError(
            f"repository is {total_bytes} bytes, above the {MAX_REPO_BYTES} limit"
        )
    return target


def install_dependencies(
    spec: RepoSpec,
    tree: Path,
    timeout: int = DEFAULT_INSTALL_TIMEOUT,
) -> dict[str, str]:
    """Install the repository's declared runtime and test dependencies.

    Dependencies go into a private directory under the clone so the host
    environment is never modified. Returns a record of what was installed.
    """

    if not spec.install_targets:
        return {"mode": "none", "targets": "", "detail": "no dependencies requested"}

    target = tree / ".acv-deps"
    target.mkdir(parents=True, exist_ok=True)
    base = [
        "install",
        "--target",
        str(target),
        "--quiet",
        *spec.install_targets,
    ]
    attempts: list[list[str]] = []
    if shutil.which("uv"):
        attempts.append(["uv", "pip", *base])
    attempts.append([sys.executable, "-m", "pip", *base])

    errors: list[str] = []
    for command in attempts:
        process = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        if process.returncode == 0:
            return {
                "mode": "isolated-target",
                "targets": " ".join(spec.install_targets),
                "detail": f"installed into {target.name}",
            }
        detail = (process.stderr or process.stdout).strip()[:400]
        errors.append(f"{' '.join(command[:3])}: {detail}")

    raise RepoIntakeError("could not install dependencies:\n" + "\n".join(errors))


def _environment(spec: RepoSpec, tree: Path) -> dict[str, str]:
    """Build an import path that prefers the cloned source over anything installed.

    Both the repository root and a ``src`` directory are added, because projects
    move between flat and ``src`` layouts across releases. Adding a directory
    that does not exist is harmless, so this stays correct when live code has
    drifted away from the pinned commit.
    """

    parts: list[str] = []
    if spec.source_root:
        parts.append(str(tree / spec.source_root))
    parts.append(str(tree / "src"))
    parts.append(str(tree))
    parts.append(str(tree / ".acv-deps"))
    parts.extend(str(tree / extra) for extra in spec.python_path_extra)
    parts.append(str(spec.task_dir))

    return {
        "PATH": "/usr/local/bin:/usr/bin:/bin",
        "HOME": str(tree.parent / "scratch" / "home"),
        "TMPDIR": str(tree.parent / "scratch" / "tmp"),
        "PYTHONPATH": ":".join(parts),
        "PYTHONHASHSEED": "0",
        "PYTHONDONTWRITEBYTECODE": "1",
        "PYTHONNOUSERSITE": "1",
        "NO_PROXY": "*",
        "no_proxy": "*",
        "ACV_DATA_DIR": str(spec.task_dir),
        "ACV_TASK_ID": spec.task_id,
    }


def _prepare_scratch(tree: Path) -> Path:
    scratch = tree.parent / "scratch"
    (scratch / "home").mkdir(parents=True, exist_ok=True)
    (scratch / "tmp").mkdir(parents=True, exist_ok=True)
    return scratch


def _run(
    spec: RepoSpec,
    tree: Path,
    command: list[str],
    timeout: int,
) -> tuple[int, str]:
    scratch = _prepare_scratch(tree)
    policy = SandboxPolicy(
        timeout=float(timeout),
        cpu_seconds=max(timeout, 1),
        memory_mb=spec.memory_mb,
        file_size_mb=64,
        max_output_bytes=2_000_000,
    )
    return run_sandboxed(
        command,
        cwd=tree,
        env=_environment(spec, tree),
        policy=policy,
        scratch_dir=scratch,
    )


def run_poc(spec: RepoSpec, tree: Path) -> tuple[int, str]:
    return _run(spec, tree, [sys.executable, str(spec.poc_path)], spec.poc_timeout)


def run_functional(spec: RepoSpec, tree: Path) -> tuple[int, str]:
    return _run(
        spec,
        tree,
        [
            sys.executable,
            "-m",
            "pytest",
            str(spec.functional_target(tree)),
            "-q",
            "-p",
            "no:cacheprovider",
        ],
        spec.test_timeout,
    )


def apply_patch(tree: Path, diff: str, spec: RepoSpec) -> list[str]:
    """Apply a unified diff inside the clone and report the touched paths."""

    if not diff.strip():
        raise RepoIntakeError("diff is empty")

    check = subprocess.run(
        ["git", "apply", "--check", "-p1", "-"],
        cwd=tree,
        input=diff,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if check.returncode != 0:
        detail = (check.stderr or check.stdout).strip()[:800]
        raise RepoIntakeError(f"diff did not apply: {detail}")

    touched = [
        line[6:].split("\t", 1)[0].strip()
        for line in diff.splitlines()
        if line.startswith("+++ b/")
    ]
    blocked = [path for path in touched if _is_protected(spec, path)]
    if blocked:
        raise RepoIntakeError(
            "diff may not modify protected evidence or test paths: " + ", ".join(blocked)
        )

    apply_process = subprocess.run(
        ["git", "apply", "-p1", "-"],
        cwd=tree,
        input=diff,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if apply_process.returncode != 0:
        detail = (apply_process.stderr or apply_process.stdout).strip()[:800]
        raise RepoIntakeError(f"diff did not apply: {detail}")
    return touched


_PROTECTED_NAMES = {
    "conftest.py",
    "pytest.ini",
    "tox.ini",
    "setup.cfg",
    "pyproject.toml",
    "sitecustomize.py",
    "usercustomize.py",
}


def _is_protected(spec: RepoSpec | None, path: str) -> bool:
    parts = Path(path).parts
    if any(part in {".git", ".acv-deps"} for part in parts):
        return True
    if Path(path).name in _PROTECTED_NAMES:
        return True
    if path.startswith("tests/") or "/tests/" in path:
        return True
    return bool(spec is not None and path in spec.protected_paths)


def _inventory(tree: Path) -> list[ProjectFileInfo]:
    import hashlib

    items: list[ProjectFileInfo] = []
    for path in sorted(tree.rglob("*.py")):
        if not path.is_file() or path.is_symlink():
            continue
        relative = path.relative_to(tree).as_posix()
        if relative.startswith(".git/") or relative.startswith(".acv-deps/"):
            continue
        data = path.read_bytes()
        items.append(
            ProjectFileInfo(
                path=relative,
                bytes=len(data),
                lines=data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0),
                sha256=hashlib.sha256(data).hexdigest(),
            )
        )
    return items


def _checker_spec(spec: RepoSpec, tree: Path) -> ProjectSpec:
    """Adapt a RepoSpec to the checker layer's existing project contract."""

    return ProjectSpec(
        project_id=spec.task_id,
        title=spec.title,
        cwe=spec.cwe,
        summary=spec.summary,
        root=tree,
        vulnerable=tree,
        poc=spec.poc_path,
        functional=spec.functional_path,
        data_dir=spec.task_dir,
        checker_include=spec.checker_include,
        checker_exclude=spec.checker_exclude,
        max_files=1000,
        max_total_bytes=MAX_REPO_BYTES,
        memory_mb=spec.memory_mb,
        poc_timeout=spec.poc_timeout,
        test_timeout=spec.test_timeout,
        tags=(),
        candidates=(),
    )


def run_checkers(spec: RepoSpec, tree: Path) -> dict[str, CheckerResult]:
    return run_project_checkers(_checker_spec(spec, tree), tree)


def _select_primary(
    results: dict[str, CheckerResult], name: str
) -> tuple[CheckerResult, str]:
    primary = results.get(name)
    if primary is None or not primary.available:
        return results["acv-rules"], "acv-rules"
    return primary, name


def _finding_key(finding: CheckFinding) -> tuple[str, str, str]:
    """Identity of a finding that survives line shifts but not new code.

    Line numbers are deliberately excluded: a patch that inserts an import
    moves every later finding down, and that is not a new weakness.
    """

    return (finding.path or "", finding.rule_id, finding.message)


def new_findings(
    baseline: dict[str, CheckerResult],
    patched: dict[str, CheckerResult],
) -> dict[str, CheckerResult]:
    """Keep only findings that the patch introduced.

    A real repository already contains code a generic rule pack flags, and none
    of it is the patch author's responsibility. Blocking on pre-existing
    findings makes a correct fix impossible to accept, so the gate compares the
    baseline against the patched scan and judges the difference.
    """

    result: dict[str, CheckerResult] = {}
    for name, after in patched.items():
        before = baseline.get(name)
        before_keys = (
            {_finding_key(finding) for finding in before.findings} if before else set()
        )
        introduced = [
            finding for finding in after.findings if _finding_key(finding) not in before_keys
        ]
        result[name] = replace(after, findings=introduced)
    return result


def _clip(text: str, limit: int = 4000) -> str:
    stripped = text.strip()
    return stripped if len(stripped) <= limit else stripped[-limit:]


def evaluate_repo(
    spec: RepoSpec,
    *,
    diff: str = "",
    checker: str = "acv-rules",
    provenance: dict[str, str] | None = None,
) -> RepoResult:
    """Judge one patch against one real repository.

    The order matters. The oracle runs on the unpatched clone first: if the PoC
    cannot reproduce the vulnerability there, no patch can be credited with
    fixing it, and the run is rejected. The checker is also run on the unpatched
    clone so the verdict reflects only findings the patch introduces.
    """

    started = time.perf_counter()
    tree = clone(spec)
    try:
        install_dependencies(spec, tree)

        oracle_exit, oracle_output = run_poc(spec, tree)
        oracle_verdict = classify_poc(oracle_exit, oracle_output)
        if spec.clean_baseline:
            oracle_ok = oracle_verdict == "blocked"
        else:
            oracle_ok = oracle_verdict == "vulnerable"
        baseline_checks = run_checkers(spec, tree)

        changed: list[str] = []
        if diff.strip():
            changed = apply_patch(tree, diff, spec)

        poc_exit, poc_output = run_poc(spec, tree)
        poc_verdict = classify_poc(poc_exit, poc_output)
        behavior_exit, behavior_output = run_functional(spec, tree)
        patched_checks = run_checkers(spec, tree)
        checker_results = new_findings(baseline_checks, patched_checks)
        primary, checker_tool = _select_primary(checker_results, checker)

        security_pass = poc_verdict == "blocked"
        behavior_pass = behavior_exit == 0
        checker_pass = primary.passed and primary.coverage_complete
        accepted = oracle_ok and security_pass and behavior_pass and checker_pass

        reasons: list[str] = []
        if not oracle_ok:
            if spec.clean_baseline:
                reasons.append(
                    f"clean baseline verification failed: security check did not report clean (verdict {oracle_verdict})"
                )
            else:
                reasons.append(
                    f"oracle did not reproduce on the real repository (verdict {oracle_verdict})"
                )
        if poc_verdict == "vulnerable":
            reasons.append("PoC still succeeds after the patch")
        elif poc_verdict == "error":
            reasons.append("PoC could not reach a verdict: the patched code crashed")
        if behavior_exit != 0:
            reasons.append("the repository's own test suite fails")
        if not primary.passed:
            ids = ", ".join(sorted({finding.rule_id for finding in primary.blocking}))
            reasons.append(f"checker findings: {ids or 'unavailable'}")
        elif not primary.coverage_complete:
            reasons.append("checker coverage is incomplete")

        files = _inventory(tree)
        return RepoResult(
            task_id=spec.task_id,
            title=spec.title,
            cwe=spec.cwe,
            repo_url=spec.repo_url,
            commit=spec.commit,
            run_id=uuid.uuid4().hex,
            input_mode="diff" if diff.strip() else "baseline",
            clone_dir=str(tree),
            files=files,
            total_files=len(files),
            total_bytes=sum(item.bytes for item in files),
            total_lines=sum(item.lines for item in files),
            changed_files=sorted(changed),
            poc_exit=poc_exit,
            poc_verdict=poc_verdict,
            poc_output=_clip(poc_output),
            behavior_exit=behavior_exit,
            behavior_output=_clip(behavior_output),
            security_pass=security_pass,
            behavior_pass=behavior_pass,
            checker_pass=checker_pass,
            accepted=accepted,
            oracle_exit=oracle_exit,
            oracle_verdict=oracle_verdict,
            oracle_output=_clip(oracle_output),
            oracle_ok=oracle_ok,
            reasons=reasons,
            findings=primary.findings,
            checker_tool=checker_tool,
            checker_results=checker_results,
            findings_truncated=any(r.truncated for r in checker_results.values()),
            elapsed_ms=int((time.perf_counter() - started) * 1000),
            provenance=provenance or {},
        )
    finally:
        shutil.rmtree(tree, ignore_errors=True)
